"""
This file is to download and prepare images from the QuickDraw dataset generated by Google to 
train a NN classifier for some categories to classify and identify simplistic drawings of objects.

How to use this file: 
    python3 download_data.py                 

We selected two categories of drawings Moon and Star. 
This file will output a compressed file with the images and labels which we will later use to train our
diffusion model. The images are 28x28 grayscale images of white strokes on a black background. 
The labels are integers corresponding to the categories, 0 for Moon and 1 for star. 

We may also select any other categories from Quickdraw dataset but
selecting Moon and Star is a simple example to demonstrate while simultaenously reducing
the complexity of our problem for the Diffusion Model. 

"""
import argparse
import ast
import os
import random
import struct
import sys
import urllib.request
import zipfile

BASE_URL = "https://storage.googleapis.com/quickdraw_dataset/full/numpy_bitmap/{}.npy"
DATA_DIR = "data"
PIXELS = 28 * 28


# --------------------------------------------------------------------------
# Downloading
# --------------------------------------------------------------------------
def _progress(blocks, block_size, total):
    if total > 0:
        done = min(blocks * block_size, total)
        pct = done * 100 // total
        sys.stdout.write(f"\r    {pct:3d}%  ({done // 1_000_000} / {total // 1_000_000} MB)")
        sys.stdout.flush()


def download_category(name):
    """Download one category's .npy file (skips if already downloaded)."""
    os.makedirs(DATA_DIR, exist_ok=True)
    path = os.path.join(DATA_DIR, f"{name}.npy")
    if os.path.exists(path):
        print(f"[skip] {path} already exists")
        return path
    url = BASE_URL.format(name.replace(" ", "%20"))
    print(f"[download] {url}")
    tmp = path + ".part"
    try:
        urllib.request.urlretrieve(url, tmp, reporthook=_progress)
    except Exception as e:
        if os.path.exists(tmp):
            os.remove(tmp)
        raise SystemExit(f"\nDownload failed for '{name}': {e}\n"
                         "Check the category name and your internet connection.")
    os.replace(tmp, path)          # only keep complete downloads
    print()
    return path


# --------------------------------------------------------------------------
# Reading / writing the .npy format by hand
# --------------------------------------------------------------------------
def read_npy_header(f):
    """Return (shape, data_offset) for an uint8 .npy file."""
    if f.read(6) != b"\x93NUMPY":
        raise ValueError("not a .npy file")
    major = f.read(2)[0]
    header_len = struct.unpack("<H" if major == 1 else "<I",
                               f.read(2 if major == 1 else 4))[0]
    header = ast.literal_eval(f.read(header_len).decode("latin1"))
    if header["descr"] not in ("|u1", "<u1", "u1"):
        raise ValueError(f"unexpected dtype {header['descr']}")
    return header["shape"], f.tell()


def npy_bytes(descr, shape, data):
    """Build a version-1.0 .npy file in memory."""
    header = "{'descr': '%s', 'fortran_order': False, 'shape': %s, }" % (descr, repr(shape))
    pad = 64 - (10 + len(header) + 1) % 64
    header = header + " " * pad + "\n"
    return b"\x93NUMPY\x01\x00" + struct.pack("<H", len(header)) + header.encode("latin1") + data


def sample_drawings(path, n, rng):
    """Pick n random drawings from a category file without loading it all."""
    with open(path, "rb") as f:
        shape, offset = read_npy_header(f)
        total = shape[0]
        idx = sorted(rng.sample(range(total), min(n, total)))
        chunks = []
        for i in idx:
            f.seek(offset + i * PIXELS)
            chunks.append(f.read(PIXELS))
    return b"".join(chunks), len(idx), total


# --------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--categories", nargs="+", default=["star", "moon"])
    parser.add_argument("--n", type=int, default=10_000,
                        help="drawings to keep per category")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    rng = random.Random(args.seed)
    images, labels, count = [], [], 0

    for label, name in enumerate(args.categories):
        path = download_category(name)
        data, kept, total = sample_drawings(path, args.n, rng)
        images.append(data)
        labels.append(struct.pack(f"<{kept}q", *([label] * kept)))
        count += kept
        print(f"[ok] {name}: kept {kept} of {total} drawings")

    width = max(len(c) for c in args.categories)
    # Fixed-width unicode strings, padded with zero bytes (numpy's own format).
    cats = b"".join(c.encode("utf-32-le") + b"\x00" * 4 * (width - len(c))
                    for c in args.categories)

    out = os.path.join(DATA_DIR, "quickdraw.npz")
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED) as z:
        z.writestr("images.npy", npy_bytes("|u1", (count, 28, 28), b"".join(images)))
        z.writestr("labels.npy", npy_bytes("<i8", (count,), b"".join(labels)))
        z.writestr("categories.npy",
                   npy_bytes(f"<U{width}", (len(args.categories),), cats))
    print(f"[saved] {out}: {count} images of shape (28, 28)")


if __name__ == "__main__":
    main()
